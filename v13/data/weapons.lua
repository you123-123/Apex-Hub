A.Weaponsfunctions = {}

function A.Weaponsfunctions.GetWeapon(name)
    for _, wep in ipairs(A.Weapons.All) do
        if wep.Name == name then
            return wep
        end
    end
    return nil
end

function A.Weaponsfunctions.GetWeaponType(name)
    local wep = A.Weaponsfunctions.GetWeapon(name)
    if wep then
        return wep.Type
    end
    return "Unknown"
end

function A.Weaponsfunctions.GetWeaponDamage(name)
    local wep = A.Weaponsfunctions.GetWeapon(name)
    if wep then
        return wep.Damage or 0
    end
    return 0
end

function A.Weaponsfunctions.GetWeaponSkills(name)
    local wep = A.Weaponsfunctions.GetWeapon(name)
    if wep then
        local skills = {}
        if wep.Key1 and wep.Key1 ~= "" then table.insert(skills, wep.Key1) end
        if wep.Key2 and wep.Key2 ~= "" then table.insert(skills, wep.Key2) end
        if wep.Key3 and wep.Key3 ~= "" then table.insert(skills, wep.Key3) end
        if wep.Key4 and wep.Key4 ~= "" then table.insert(skills, wep.Key4) end
        return skills
    end
    return {}
end

function A.Weaponsfunctions.GetBestWeapon(type)
    local best = nil
    local bestScore = 0
    for _, wep in ipairs(A.Weapons.All) do
        if wep.Type == type then
            local rarityScore = A.Weapons.RarityOrder[wep.Rarity] or 1
            local score = wep.Damage * wep.Speed * rarityScore
            if score > bestScore then
                bestScore = score
                best = wep
            end
        end
    end
    return best
end

function A.Weaponsfunctions.GetWeaponByMastery(type)
    local best = nil
    local bestMastery = 0
    for _, wep in ipairs(A.Weapons.All) do
        if wep.Type == type and wep.Mastery > bestMastery then
            bestMastery = wep.Mastery
            best = wep
        end
    end
    return best
end

function A.Weaponsfunctions.CompareWeapons(w1Name, w2Name)
    local w1 = A.Weaponsfunctions.GetWeapon(w1Name)
    local w2 = A.Weaponsfunctions.GetWeapon(w2Name)
    if not w1 or not w2 then return nil end
    local r1 = A.Weapons.RarityOrder[w1.Rarity] or 1
    local r2 = A.Weapons.RarityOrder[w2.Rarity] or 1
    local score1 = w1.Damage * w1.Speed * r1
    local score2 = w2.Damage * w2.Speed * r2
    return {
        Weapon1 = w1Name,
        Weapon2 = w2Name,
        Score1 = score1,
        Score2 = score2,
        Winner = score1 > score2 and w1Name or w2Name,
        DamageDiff = w1.Damage - w2.Damage,
        SpeedDiff = w1.Speed - w2.Speed,
    }
end

function A.Weaponsfunctions.GetWeaponDPS(name)
    local wep = A.Weaponsfunctions.GetWeapon(name)
    if wep then
        local cooldown = 1.5 / wep.Speed
        return wep.Damage / cooldown
    end
    return 0
end

function A.Weaponsfunctions.GetWeaponsByRarity(rarity)
    local result = {}
    for _, wep in ipairs(A.Weapons.All) do
        if wep.Rarity == rarity then
            table.insert(result, wep)
        end
    end
    return result
end

function A.Weaponsfunctions.HasWeapon(name)
    if A.Inventory and A.Inventory.Weapons then
        for _, wep in ipairs(A.Inventory.Weapons) do
            if wep == name then
                return true
            end
        end
    end
    return false
end

function A.Weaponsfunctions.GetEquippedWeapon()
    if A.Player and A.Player.Character then
        local tool = A.Player.Character:FindFirstChildOfClass("Tool")
        if tool then
            return A.Weaponsfunctions.GetWeapon(tool.Name)
        end
    end
    return nil
end

function A.Weaponsfunctions.GetWeaponLocation(name)
    local wep = A.Weaponsfunctions.GetWeapon(name)
    if wep then
        return wep.Location
    end
    return "Unknown"
end

function A.Weaponsfunctions.GetWeaponCost(name)
    local wep = A.Weaponsfunctions.GetWeapon(name)
    if wep then
        return wep.Price
    end
    return 0
end

function A.Weaponsfunctions.CanObtain(name)
    local wep = A.Weaponsfunctions.GetWeapon(name)
    if not wep then return false end
    if wep.Obtained == "Default" then return true end
    if wep.Obtained == "Gamepass" then return false end
    if A.Player and A.Player.Data and A.Player.Data.Level.Value >= wep.RequiredLevel then
        return true
    end
    return false
end

function A.Weaponsfunctions.GetWeaponTier(name)
    local wep = A.Weaponsfunctions.GetWeapon(name)
    if not wep then return 0 end
    local rarity = A.Weapons.RarityOrder[wep.Rarity] or 1
    local damageTier = math.floor(wep.Damage / 50)
    return rarity + damageTier
end

function A.Weaponsfunctions.GetWeaponsForPvP()
    local pvpWeapons = {}
    for _, wep in ipairs(A.Weapons.All) do
        local rarity = A.Weapons.RarityOrder[wep.Rarity] or 1
        if rarity >= 3 and wep.Speed >= 1.4 then
            table.insert(pvpWeapons, wep)
        end
    end
    table.sort(pvpWeapons, function(a, b)
        return a.Damage * a.Speed > b.Damage * b.Speed
    end)
    return pvpWeapons
end

function A.Weaponsfunctions.GetWeaponsForPvE()
    local pveWeapons = {}
    for _, wep in ipairs(A.Weapons.All) do
        if wep.Damage >= 100 then
            table.insert(pveWeapons, wep)
        end
    end
    table.sort(pveWeapons, function(a, b) return a.Damage > b.Damage end)
    return pveWeapons
end

